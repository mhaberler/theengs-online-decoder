'use strict';

// Generate sensor-ble-decoders/theengs.js: a self-contained sensor-ble custom
// decoder (Sensor Logger contract — no import/require, single file) that
// decodes via the TheengsDecoder wasm. The Emscripten module from the
// theengs-decoder dependency is inlined (base64 wasm included) with its Node
// branches patched out; each patch asserts its pattern still matches, so a
// theengs-decoder bump that changes the glue fails the build loudly.
//
// Usage: node scripts/build-sensorble-theengs.js

const fs = require('node:fs');
const path = require('node:path');

const SRC = require.resolve('theengs-decoder/dist/theengs_decoder_wasm.mjs');
const VERSION = require('theengs-decoder/package.json').version;
// Bump when only the glue/patching changes; catalogs compare the full
// version (theengs-decoder version + this revision) to offer updates.
const GENERATOR_REVISION = 1;
const OUT = path.join(__dirname, '..', 'sensor-ble-decoders', 'theengs.js');

// [description, search, replacement, expected occurrence count]
const PATCHES = [
  ['script name', 'var _scriptName = import.meta.url;', 'var _scriptName = undefined;', 1],
  [
    'node detection',
    "var ENVIRONMENT_IS_NODE = typeof process == 'object' && typeof process.versions == 'object' && typeof process.versions.node == 'string';",
    'var ENVIRONMENT_IS_NODE = false;',
    1,
  ],
  [
    'createRequire',
    "const { createRequire } = await import('module');\n  /** @suppress{duplicate} */\n  var require = createRequire(import.meta.url);",
    '',
    1,
  ],
  ['node fs/path', "var fs = require('fs');\n  var nodePath = require('path');", 'var fs, nodePath;', 1],
  [
    'node scriptDirectory',
    "scriptDirectory = require('url').fileURLToPath(new URL('./', import.meta.url));",
    '',
    1,
  ],
  [
    'shell env guard',
    "(typeof process == 'object' && typeof require === 'function') || ",
    '',
    1,
  ],
  // Node (with the Node branch gone) and Sensor Logger land in the "shell"
  // environment, which this build otherwise refuses; the wasm is inlined, so
  // shell needs no file loading.
  [
    'shell assert',
    "assert(!ENVIRONMENT_IS_SHELL, 'shell environment detected but not enabled at build time.  Add `shell` to `-sENVIRONMENT` to enable.');",
    '',
    1,
  ],
  ['default export', 'export default createTheengsDecoderModule;', '', 1],
];

function patch(src) {
  for (const [what, search, replacement, count] of PATCHES) {
    const n = src.split(search).length - 1;
    if (n !== count) {
      throw new Error(`patch "${what}": expected ${count} match(es), found ${n} — glue changed?`);
    }
    src = src.split(search).join(replacement);
  }
  // Comment lines that merely mention import/require would trip a textual
  // sandbox check; they carry no code.
  src = src.replace(/^[ \t]*\/\/.*\b(import|require)\b.*\n/gm, '');
  const left = src.match(/\bimport\b|\brequire\b/g);
  if (left) throw new Error(`forbidden tokens remain after patching: ${[...new Set(left)].join(', ')}`);
  return src;
}

const HEADER = `// GENERATED by scripts/build-sensorble-theengs.js from theengs-decoder@${VERSION}
// — do not edit; re-run \`bun run build-sensorble-theengs\`.
//
// sensor-ble custom decoder that decodes any advertisement TheengsDecoder
// knows. It declares no name/manufacturer/serviceUUID; instead \`matchAll: true\`
// asks the host to offer it every advertisement, after all other decoders.
// Hosts that don't know \`matchAll\` (e.g. Sensor Logger today) never match it.
//
// License: GPL-3.0-only (TheengsDecoder).
`;

const GLUE = `
const MAC_RE = /^([0-9a-f]{2}:){5}[0-9a-f]{2}$/i;
// Input fields TheengsDecoder echoes back into its output.
const ECHOES = ['servicedata', 'manufacturerdata', 'servicedatauuid', 'name', 'id'];

const theengs = new (await createTheengsDecoderModule()).TheengsDecoder();

function run(input) {
  const out = theengs.decodeBLE(JSON.stringify(input));
  if (!out) return null;
  let values;
  try { values = JSON.parse(out); } catch { return null; }
  for (const k of ECHOES) delete values[k];
  return Object.keys(values).length ? values : null;
}

function decodeTheengs(manufacturerData, serviceData, meta) {
  const base = {};
  if (manufacturerData && manufacturerData.length) base.manufacturerdata = manufacturerData.toString('hex');
  if (meta?.name) base.name = meta.name;
  if (meta?.id && MAC_RE.test(meta.id)) base.id = meta.id;

  const uuids = Object.keys(serviceData ?? {});
  for (const uuid of uuids) {
    const input = { ...base, servicedata: serviceData[uuid].toString('hex') };
    if (/^[0-9a-f]{4}$/i.test(uuid)) input.servicedatauuid = '0x' + uuid.toLowerCase();
    const values = run(input);
    if (values) return values;
  }
  return base.manufacturerdata ? run(base) : null;
}

export const decoder = {
  decoderName: 'theengs',
  matchAll: true,
  variableFormat: true,
  advertisementDecode: decodeTheengs,

  // Catalog metadata (ignored by hosts that don't know it).
  title: 'TheengsDecoder (all supported devices)',
  description: 'Decodes every device TheengsDecoder supports. A catch-all fallback (matchAll): tried after all other decoders; hosts without matchAll, such as Sensor Logger today, never use it.',
  version: '${VERSION}.${GENERATOR_REVISION}',
  author: 'Theengs / Michael Haberler (packaging)',
  license: 'GPL-3.0-only',
  tags: ['theengs', 'catch-all'],
};

// Regression vectors for catalog builds: a Xiaomi RoPot service-data advert,
// and a payload no Theengs model matches.
export const tests = [
  {
    given: {
      serviceData: { fe95: '71205d0183d20c6d8d7cc40d08100103' },
      meta: { name: 'x', id: 'AA:BB:CC:DD:EE:FF' },
    },
    expected: {
      brand: 'Xiaomi', model: 'RoPot', model_id: 'HHCCPOT002', type: 'PLANT',
      moi: 3, mac: 'C4:7C:8D:6D:0C:D2',
    },
  },
  { given: { manufacturerData: 'ffff00' }, expected: null },
];
`;

function build() {
  const body = patch(fs.readFileSync(SRC, 'utf8'));
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, HEADER + body + GLUE);
  return OUT;
}

module.exports = { build, OUT };

if (require.main === module) {
  const out = build();
  console.log(`wrote ${path.relative(process.cwd(), out)} (${fs.statSync(out).size} bytes)`);
}
